#!/usr/bin/env bash
# serve.sh -- serve the browser prototype (native/web) on this machine only (127.0.0.1).
#
#   tools/byo/serve.sh [python] [--port N]   python3 http.server, default port 8000 (no Docker)
#   tools/byo/serve.sh docker   [--port N]   nginx + the optional Report backend, default 8796
#   tools/byo/serve.sh docker-down           stop the Docker option
#
# Run tools/byo/build_web.sh first: it writes native/web/data from your own disc.
# The python option is a plain static server: the pages work, the Report button (R) can't
# save (its backend, tools/byo/report_api.py, only runs in the Docker option).
# The Docker option writes its compose file to tools/byo/serve-docker/ (gitignored) and saves
# reports to tools/byo/serve-docker/reports/. Both bind to 127.0.0.1 only.
set -euo pipefail
REPO=$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)
WEB=$REPO/native/web
MODE=python; PORT=""
while [ $# -gt 0 ]; do
  case "$1" in
    python|docker|docker-down) MODE=$1 ;;
    --port) [ $# -ge 2 ] || { echo "usage: serve.sh [python|docker] [--port N]" >&2; exit 2; }; PORT=$2; shift ;;
    -h|--help) sed -n '2,12p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) echo "unknown argument $1 (try --help)" >&2; exit 2 ;;
  esac
  shift
done
D=$REPO/tools/byo/serve-docker

if [ "$MODE" = docker-down ]; then
  [ -f "$D/compose.yaml" ] || { echo "nothing to stop ($D/compose.yaml missing)"; exit 0; }
  exec docker compose -f "$D/compose.yaml" down
fi

[ -f "$WEB/data/scene.json" ] && [ -f "$WEB/data/vincent/vincent.glb" ] ||
  { echo "native/web/data is missing or incomplete: run tools/byo/build_web.sh <your.iso> first" >&2; exit 1; }

if [ "$MODE" = python ]; then
  PORT=${PORT:-8000}
  echo "Serving $WEB on http://127.0.0.1:$PORT/  (Ctrl+C to stop)"
  echo "  viewer: http://127.0.0.1:$PORT/index.html   play: http://127.0.0.1:$PORT/play.html"
  echo "  (Report button: no backend in this mode, use 'serve.sh docker' if you want it)"
  exec python3 -m http.server --bind 127.0.0.1 --directory "$WEB" "$PORT"
fi

# ---- docker: generated files, gitignored by the repo's default-deny .gitignore
command -v docker >/dev/null || { echo "docker not found; use 'tools/byo/serve.sh' (python) instead" >&2; exit 1; }
docker compose version >/dev/null 2>&1 || { echo "'docker compose' (v2) not found" >&2; exit 1; }
PORT=${PORT:-8796}
git -C "$REPO" check-ignore -q tools/byo/serve-docker/compose.yaml ||
  { echo "tools/byo/serve-docker is not gitignored; refusing to write there" >&2; exit 1; }
mkdir -p "$D/reports"
cat > "$D/nginx.conf" <<'EOF'
server {
    listen 80;
    root /usr/share/nginx/html;
    index index.html;
    gzip on;
    gzip_types application/octet-stream application/json application/javascript text/css;
    gzip_min_length 1024;
    location = /api/report {
        client_max_body_size 20m;
        client_body_buffer_size 20m;
        proxy_pass http://dirge-report:8000;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_read_timeout 30s;
    }
    location /api/ { return 404; }
    location / {
        try_files $uri $uri/ =404;
        add_header Cache-Control "no-cache";
    }
}
EOF
cat > "$D/compose.yaml" <<EOF
# generated by tools/byo/serve.sh (gitignored). Local only: 127.0.0.1:$PORT.
name: dirge-byo
services:
  dirge-play:
    image: nginx:1.27-alpine
    restart: unless-stopped
    volumes:
      - $WEB:/usr/share/nginx/html:ro
      - ./nginx.conf:/etc/nginx/conf.d/default.conf:ro
    ports:
      - "127.0.0.1:$PORT:80"
    depends_on: [dirge-report]
  dirge-report:
    image: python:3.12-alpine
    restart: unless-stopped
    user: "$(id -u):$(id -g)"
    command: ["python3", "-I", "/app/report_api.py"]
    environment:
      REPORTS_DIR: /reports
    volumes:
      - $REPO/tools/byo/report_api.py:/app/report_api.py:ro
      - ./reports:/reports
EOF
docker compose -f "$D/compose.yaml" up -d
echo "Serving on http://127.0.0.1:$PORT/  (index.html viewer, play.html)."
echo "Reports go to $D/reports/. Stop with: tools/byo/serve.sh docker-down"
